BANNED = re.compile(r"наруш|правил[оау]?\b|должен|обязан|запрещ|не допускается|положено", re.I)


def llm(system: str, user: str) -> str:
    key = hashlib.sha1((MODEL + system + "\x00" + user).encode()).hexdigest()
    if key not in cache:
        from openai import OpenAI
        c = OpenAI(base_url=config.REWRITE_BASE_URL, api_key=config.REWRITE_API_KEY)
        r = c.chat.completions.create(model=MODEL, max_tokens=8000, messages=[
            {"role": "system", "content": system}, {"role": "user", "content": user}])
        cache[key] = r.choices[0].message.content or ""
    return cache[key]


def tag(text: str, name: str) -> str:
    m = re.findall(fr"<{name}>(.*?)</{name}>", text, re.S)
    return m[-1].strip() if m else ""


clauses = {}
for ch in load_chunks():
    clauses.setdefault(f"{ch['doc_code']}:{ch['clause']}", (ch["doc_short"], ch["clause_label"], []))[2].append(ch["text"])
text = {k: "\n".join(dict.fromkeys(v[2])) for k, v in clauses.items()}
catalog = "\n".join(f"{k} {v[:160]}".replace("\n", " ") for k, v in text.items())


def make(job: tuple) -> dict:
    i, key, hint = job
    for attempt in range(3):
        salt = f"\n(вариант {attempt})" if attempt else ""
        if key:
            log = tag(llm(GEN, f"Пункт {key}:\n{text[key]}\n\nСитуация: {hint}{salt}"), "log")
        else:
            log = tag(llm(GEN_CLEAN, f"Операция: {hint}{salt}"), "log")
        if not log or BANNED.search(log):
            continue
        v = tag(llm(VERIFY, f"Пункт: {key + chr(10) + text[key] if key else 'нет'}\n\nЖурнал:\n{log}\n\nКаталог:\n{catalog}"), "json")
        try:
            v = json.loads(v)
        except json.JSONDecodeError:
            continue
        if v.get("leak") or (key and not v.get("shows")):
            continue
        also = [a for a in v.get("also") or [] if a in text and a != key]
        name = f"{ACT_NO[key.split(':')[0]]}_{key.split(':')[1]}" if key else "clean"
        return {"id": f"gen{i:02d}_{name}", "expect": [key] if key else [],
                "also": also, "hint": hint, "moment": v.get("moment", ""), "log": log + "\n"}
    return {"id": f"gen{i:02d}_dropped", "dropped": True, "hint": hint, "expect": [key] if key else []}


jobs = [(i, k, h) for i, (k, h) in enumerate(TARGETS)] + [(len(TARGETS) + i, None, h) for i, h in enumerate(CLEAN)]
with cf.ThreadPoolExecutor(8) as ex:
    out = list(ex.map(make, jobs))
json.dump(cache, open(CACHE_PATH, "w"), ensure_ascii=False)
kept = [c for c in out if not c.get("dropped")]
for c in out:
    if c.get("dropped"):
        print("DROPPED", c["expect"], c["hint"])


class Block(yaml.SafeDumper):
    pass


Block.add_representer(str, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None))
with open(f"{D}/timelines_gen.yaml", "w") as f:
    f.write(f"# Generated by gen_tests.py ({MODEL} writes, {MODEL} verifies). expect = target clause, "
            "also = other clauses the verifier saw broken; expect [] = clean log.\n")
    yaml.dump({"cases": kept}, f, Dumper=Block, allow_unicode=True, sort_keys=False, width=200)
print(f"kept {len(kept)}/{len(out)}")
